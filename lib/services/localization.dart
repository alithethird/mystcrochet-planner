import 'package:flutter/foundation.dart';

enum AppLanguage {
  tr,
  en,
  de,
  es,
}

extension AppLanguageExtension on AppLanguage {
  String get code => name;

  String get label {
    switch (this) {
      case AppLanguage.tr:
        return 'Türkçe';
      case AppLanguage.en:
        return 'English';
      case AppLanguage.de:
        return 'Deutsch';
      case AppLanguage.es:
        return 'Español';
    }
  }

  String get flag {
    switch (this) {
      case AppLanguage.tr:
        return '🇹🇷';
      case AppLanguage.en:
        return '🇬🇧';
      case AppLanguage.de:
        return '🇩🇪';
      case AppLanguage.es:
        return '🇪🇸';
    }
  }

  String get shortName => name.toUpperCase();
}

class LocalizationService extends ChangeNotifier {
  static final LocalizationService _instance = LocalizationService._internal();
  factory LocalizationService() => _instance;
  LocalizationService._internal();

  AppLanguage _currentLanguage = AppLanguage.tr;

  AppLanguage get currentLanguage => _currentLanguage;
  bool get isTr => _currentLanguage == AppLanguage.tr;

  void toggleLanguage() {
    cycleLanguage();
  }

  void cycleLanguage() {
    final values = AppLanguage.values;
    final nextIndex = (values.indexOf(_currentLanguage) + 1) % values.length;
    setLanguage(values[nextIndex]);
  }

  void setLanguage(AppLanguage lang) {
    if (_currentLanguage != lang) {
      _currentLanguage = lang;
      notifyListeners();
    }
  }

  String tr(String key) {
    final map = switch (_currentLanguage) {
      AppLanguage.tr => _trMap,
      AppLanguage.en => _enMap,
      AppLanguage.de => _deMap,
      AppLanguage.es => _esMap,
    };
    return map[key] ?? _enMap[key] ?? key;
  }

